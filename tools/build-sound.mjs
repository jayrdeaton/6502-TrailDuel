// Builds src/sounddata.inc: the sounds of Trap, TrailDuel's version in DuelTastic,
// rewritten for the SID's three voices. The app's are WAVs; these follow their notes,
// lengths and shapes (DuelTastic's assets/sounds). Run with `make sound`.
// The step format and its helpers are 6502-HexFleet's (its tools/build-sound.mjs).
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const reg = hz => Math.min(0xffff, Math.round(hz * 16.777216))
const midi = m => 440 * 2 ** ((m - 69) / 12)
const WAVE = { tri: 0x10, saw: 0x20, pulse: 0x40, noise: 0x80 }
const C5 = midi(72), D5 = midi(74), E5 = midi(76), G5 = midi(79), A5 = midi(81), AS5 = midi(82)
const C6 = midi(84), E6 = midi(88), G6 = midi(91)

// The filter's cutoff register for a pitch, by the emulator's curve for the chip.
const cutoff = hz => Math.round(Math.sqrt(Math.max(0, hz - 30) / 11970) * 255.875)

// One step of an effect, n frames long. hz is a pitch; for noise, `rate` is the raw
// register. `to` slides toward another pitch, each frame by 1/2^k of the way there.
// `keep` carries on from the last pitch, and `off` lets the note go (or keeps a voice
// quiet while it waits its turn). `lp` sends the voice through the low-pass filter
// from that pitch, closing by 1/2^close of itself a frame.
//
// A SID voice always climbs toward full volume, so a quiet note is one let go early:
// attack for a frame and release, and it only gets part of the way up.
const step = ({ n, w, a = 0, d = 0, s = 0, r = 0, hz = 0, rate, to, toRate, k = 0, retrig = false, keep = false, off = false, pw = 8, lp = 0, close = 0 }) => {
  const from = keep ? 0 : (rate ?? reg(hz))
  const target = keep ? 0 : (toRate ?? (to === undefined ? from : reg(to)))
  return [n, WAVE[w] | (off ? 0 : 1), (a << 4) | d, (s << 4) | r, from & 255, from >> 8, target & 255, target >> 8, k | (retrig ? 0x10 : 0) | (keep ? 0x80 : 0), pw, lp ? cutoff(lp) : 0, close]
}
// A short note: up for one frame on attack `a`, then let go on release `r`.
const blip = (w, hz, a, r, n) => [{ n: 1, w, hz, a, s: 15, r, retrig: true }, { n, w, a, s: 15, r, keep: true, off: true }]
// A voice waiting n frames before its note
const wait = n => ({ n, w: 'tri', off: true })
// A struck note, n frames long: up for a frame on attack `a` (the slower, the quieter),
// then ringing away on release `r`
const ring = (hz, n, a, r, w = 'tri', more = {}) => [{ n: 1, w, hz, a, s: 15, r, retrig: true, ...more }, { n: n - 1, w, a, s: 15, r, keep: true, off: true, ...more }]
const go = steps => [...steps.flat().flatMap(step), 0]

// name: priority, voice (0-2), another voice it may take (1-3, or 0), an effect to
// start with it on another voice, and its steps. Louder sounds take a voice from
// quieter ones; the round's end takes all three.
const FX = {
  // A person turning: a 50 ms blip near A#5 (turn.wav)
  TURN: [2, 0, 2, 0, go(blip('tri', AS5, 3, 2, 2))],
  // The menu: a 60 ms A5 (select.wav)
  SELECT: [2, 0, 2, 0, go(blip('tri', A5, 3, 2, 2))],
  // A round starts: C major fading over 0.65 s, C5 low with C6 in it, E6 and G6 (countdownGo.wav)
  GO: [5, 0, 0, 'GO_E', go([ring(C5, 40, 7, 9, 'pulse', { pw: 4 })])],
  GO_E: [5, 1, 0, 'GO_G', go([ring(E6, 40, 7, 9)])],
  GO_G: [5, 2, 0, 0, go([ring(G6, 40, 7, 9)])],
  // A crash: a crack, then a tone falling from 390 Hz toward 200 as it dies, a thud
  // under it falling from 108 Hz (crash.wav)
  CRASH: [7, 2, 0, 'THUD', go([{ n: 1, w: 'noise', rate: 0x6000, a: 5, s: 15, r: 2, retrig: true, lp: 1600 }, { n: 1, w: 'noise', a: 5, s: 15, r: 2, keep: true, off: true, lp: 1600 }, ring(390, 34, 4, 9, 'saw', { to: 200, k: 4, lp: 1100, close: 4 })])],
  THUD: [7, 1, 0, 0, go([ring(108, 30, 5, 8, 'tri', { to: 72, k: 3 })])],
  // A win: C5, E5, G5 and C6 80 ms apart, E6 ringing on over them (win.wav)
  WIN: [8, 0, 0, 'WIN_E', go([ring(C5, 14, 6, 6), ring(C6, 70, 6, 10)])],
  WIN_E: [8, 1, 0, 'WIN_G', go([wait(5), ring(E5, 14, 5, 7), ring(E6, 90, 5, 10)])],
  WIN_G: [8, 2, 0, 0, go([wait(10), ring(G5, 60, 6, 7)])],
  // A draw, or a round lost: A5, and D5 under it 150 ms on, both ringing a second (draw.wav)
  DRAW: [8, 0, 0, 'DRAW_D', go([ring(A5, 60, 4, 10)])],
  DRAW_D: [8, 1, 0, 0, go([wait(9), ring(D5, 51, 5, 10)])]
}

// --- Output ---
const hex = b => '$' + (b & 255).toString(16).toUpperCase().padStart(2, '0')
const rows = bytes => { const out = []; for (let i = 0; i < bytes.length; i += 16) out.push('  .byte ' + bytes.slice(i, i + 16).map(hex).join(',')); return out.join('\n') }
const names = Object.keys(FX)
const id = n => (n ? names.indexOf(n) + 1 : 0)
const lines = ['; =============================================================================', ';   sounddata.inc - GENERATED by tools/build-sound.mjs (make sound).', ';   Do not edit by hand: change the script and run it again.', '; =============================================================================', '']
names.forEach((n, i) => lines.push(`SFX_${n} = ${i + 1}`))
lines.push(`SFX_COUNT = ${names.length}`, '', '.segment "BANK00"', '')
lines.push('; Indexed by effect number (0 is nothing)')
const col = (label, f) => lines.push(label + ':', rows([0, ...names.map(f)]))
col('FxPrio', n => FX[n][0]); col('FxVoice', n => FX[n][1]); col('FxOther', n => FX[n][2]); col('FxPair', n => id(FX[n][3]))
lines.push('FxLo:', '  .byte 0' + names.map(n => `, <Fx${n}`).join(''), 'FxHi:', '  .byte 0' + names.map(n => `, >Fx${n}`).join(''))
for (const n of names) lines.push(`Fx${n}:`, rows(FX[n][4]))
writeFileSync(join(root, 'src/sounddata.inc'), lines.join('\n') + '\n')
console.log(`src/sounddata.inc: ${names.length} effects`)
